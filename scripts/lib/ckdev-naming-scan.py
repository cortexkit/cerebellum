#!/usr/bin/env python3
"""Reject test and script executions of production-named ck-* binaries.

Rust test-code regions and tokens come from durable-journal-scan.py so comments,
strings, inline tests, and out-of-line test modules follow the same code-aware
rules as the other source guards. Each Command::new argument and each configured
module program is checked independently; a helper call in a neighboring
statement cannot make a direct spawn safe.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path
from typing import Dict, List, Set, Tuple

# Importing the shared tokenizer must not leave generated bytecode in the tree.
sys.dont_write_bytecode = True
SCANNER_PATH = Path(__file__).with_name("durable-journal-scan.py")
SPEC = importlib.util.spec_from_file_location("durable_journal_scan", SCANNER_PATH)
if SPEC is None or SPEC.loader is None:
    raise RuntimeError(f"could not load shared Rust source scanner at {SCANNER_PATH}")
SHARED = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(SHARED)

Token = Tuple[str, str, int]
HELPERS = {"ckdev_binary"}


def _matching(tokens: List[Token], start: int) -> int:
    return SHARED._matching(tokens, start)


def _contains_helper(tokens: List[Token], start: int, end: int) -> bool:
    return any(kind == "ident" and text in HELPERS for kind, text, _ in tokens[start:end])


def _source_binary(tokens: List[Token], start: int, end: int) -> bool:
    for kind, text, _ in tokens[start:end]:
        if kind == "lit" and (
            "CARGO_BIN_EXE_ck-" in text
            or re.search(r"(?:^|[/\\])ck-[A-Za-z0-9._-]+(?:$|[\"' ])", text)
        ):
            return True
    return False


def _function_helpers(tokens: List[Token]) -> Set[str]:
    helpers: Set[str] = set()
    for index in range(len(tokens) - 2):
        if tokens[index][1] != "fn" or tokens[index + 1][0] != "ident":
            continue
        name = tokens[index + 1][1]
        open_paren = next(
            (pos for pos in range(index + 2, len(tokens)) if tokens[pos][1] in ("(", "{")),
            None,
        )
        if open_paren is None or tokens[open_paren][1] != "(":
            continue
        close_paren = _matching(tokens, open_paren)
        open_brace = close_paren + 1
        while open_brace < len(tokens) and tokens[open_brace][1] != "{":
            open_brace += 1
        if open_brace >= len(tokens):
            continue
        close_brace = _matching(tokens, open_brace)
        if _contains_helper(tokens, open_brace, close_brace + 1):
            helpers.add(name)
    return helpers


def _expression_end(tokens: List[Token], start: int) -> int:
    depth = 0
    for index in range(start, len(tokens)):
        text = tokens[index][1]
        if text in ("(", "[", "{"):
            depth += 1
        elif text in (")",
            "]",
            "}",
        ):
            depth -= 1
        elif text == ";" and depth == 0:
            return index
    return len(tokens)


def _variable_states(tokens: List[Token], protected_functions: Set[str]):
    tainted: Set[str] = set()
    protected: Set[str] = set()
    for index in range(len(tokens) - 3):
        if tokens[index][1] != "let":
            continue
        name_index = index + 1
        if tokens[name_index][1] == "mut":
            name_index += 1
        if tokens[name_index][0] != "ident":
            continue
        name = tokens[name_index][1]
        equal = name_index + 1
        while equal < len(tokens) and tokens[equal][1] not in ("=", ";", "{"):
            equal += 1
        if equal >= len(tokens) or tokens[equal][1] != "=":
            continue
        end = _expression_end(tokens, equal + 1)
        helper = _contains_helper(tokens, equal + 1, end)
        from_protected_function = any(
            tokens[pos][1] in protected_functions
            and pos + 1 < end
            and tokens[pos + 1][1] == "("
            for pos in range(equal + 1, end)
        )
        inherits_taint = _source_binary(tokens, equal + 1, end) or any(
            kind == "ident" and text in tainted
            for kind, text, _ in tokens[equal + 1 : end]
        )
        if helper or from_protected_function:
            protected.add(name)
            tainted.discard(name)
        elif inherits_taint:
            tainted.add(name)
            protected.discard(name)
        else:
            tainted.discard(name)
            protected.discard(name)
    return tainted, protected


def _dangerous_expression(
    tokens: List[Token], start: int, end: int, tainted: Set[str], protected: Set[str]
) -> bool:
    if _contains_helper(tokens, start, end):
        return False
    if _source_binary(tokens, start, end):
        return True
    return any(
        kind == "ident" and text in tainted and text not in protected
        for kind, text, _ in tokens[start:end]
    )


def _command_arguments(tokens: List[Token], open_paren: int) -> Tuple[int, int]:
    close_paren = _matching(tokens, open_paren)
    depth = 0
    for index in range(open_paren + 1, close_paren):
        text = tokens[index][1]
        if text in ("(", "[", "{"):
            depth += 1
        elif text in (")",
            "]",
            "}",
        ):
            depth -= 1
        elif text == "," and depth == 0:
            return open_paren + 1, index
    return open_paren + 1, close_paren


def rust_offenders(source: str, path: str) -> List[str]:
    return rust_token_offenders(SHARED.tokenize(source), path)


def rust_token_offenders(tokens: List[Token], path: str) -> List[str]:
    protected_functions = _function_helpers(tokens)
    tainted, protected = _variable_states(tokens, protected_functions)
    offenders: Set[str] = set()

    # Check each process constructor's executable argument on its own. In
    # particular, a ckdev_binary call on the preceding line cannot bless this
    # constructor's separate, direct argument.
    for index in range(len(tokens) - 3):
        if tokens[index][1] != "Command" or tokens[index + 1][1] != ":":
            continue
        if tokens[index + 2][1] != ":" or tokens[index + 3][1] != "new":
            continue
        open_paren = index + 4
        if open_paren >= len(tokens) or tokens[open_paren][1] != "(":
            continue
        start, end = _command_arguments(tokens, open_paren)
        if _dangerous_expression(tokens, start, end, tainted, protected):
            offenders.add(
                f"{path}:{tokens[index][2]}: process constructor executes a ck-* binary without ckdev_binary"
            )

    # A daemon configuration's `program` field is also an executable site: the
    # daemon's trampoline later execs that configured path.
    for index in range(len(tokens) - 2):
        if tokens[index][0] != "lit" or tokens[index][1] != "program":
            continue
        if tokens[index + 1][1] != ":":
            continue
        start = index + 2
        depth = 0
        end = start
        while end < len(tokens):
            text = tokens[end][1]
            if text in ("(", "[", "{"):
                depth += 1
            elif text in (")",
                "]",
                "}",
            ):
                if depth == 0:
                    break
                depth -= 1
            elif text == "," and depth == 0:
                break
            end += 1
        if _dangerous_expression(tokens, start, end, tainted, protected):
            offenders.add(
                f"{path}:{tokens[index][2]}: configured program executes a ck-* binary without ckdev_binary"
            )
    return sorted(offenders)


def _expand_shell(value: str, variables: Dict[str, str], seen: Set[str] | None = None) -> str:
    seen = set() if seen is None else seen
    value = value.strip().strip("\"'")
    def strip_prefix(match):
        name, prefix = match.group(1) or "", match.group(2) or ""
        if name in seen:
            return match.group(0)
        expanded = _expand_shell(variables.get(name, name), variables, seen | {name})
        return expanded.removeprefix(prefix)

    value = re.sub(r"\$\{([A-Za-z_][A-Za-z0-9_]*)#([^}]*)\}", strip_prefix, value)

    def replace(match):
        name = match.group(1) or match.group(2) or ""
        if name in seen or name not in variables:
            return match.group(0)
        return _expand_shell(variables[name], variables, seen | {name})

    return re.sub(r"\$([A-Za-z_][A-Za-z0-9_]*)|\$\{([A-Za-z_][A-Za-z0-9_]*)\}", replace, value)


def _strip_shell_comment(line: str) -> str:
    quote = None
    escaped = False
    for index, char in enumerate(line):
        if escaped:
            escaped = False
        elif char == "\\" and quote != "'":
            escaped = True
        elif quote is not None:
            if char == quote:
                quote = None
        elif char in ("'", '\"'):
            quote = char
        elif char == "#" and (index == 0 or line[index - 1].isspace()):
            return line[:index]
    return line


def shell_offenders(source: str, path: str) -> List[str]:
    variables: Dict[str, str] = {}
    offenders: Set[str] = set()
    assignment = re.compile(r"\b([A-Za-z_][A-Za-z0-9_]*)=(\"[^\"]*\"|'[^']*'|[^;\s]+)")
    word = re.compile(r'^\s*(?:"([^"]*)"|\'([^\']*)\'|([^\s;]+))')
    heredoc: str | None = None

    for line_number, original in enumerate(source.splitlines(), 1):
        if heredoc is not None:
            if original.strip() == heredoc:
                heredoc = None
            continue
        code = _strip_shell_comment(original)
        here = re.search(r"<<-?\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\1", code)
        if here:
            heredoc = here.group(2)
        for match in assignment.finditer(code):
            variables[match.group(1)] = match.group(2)

        commands: List[str] = []
        commands.extend(re.findall(r"\$\(([^()]*)\)", code))
        # Also inspect a command which is the first shell word on the line.
        stripped = code.lstrip()
        if stripped.startswith(('"', "'", "$")) or re.match(r"[./A-Za-z_$]", stripped):
            commands.append(stripped)

        for command in commands:
            match = word.match(command)
            if match is None:
                continue
            executable = next((part for part in match.groups() if part is not None), "")
            expanded = _expand_shell(executable, variables)
            basename = expanded.rsplit("/", 1)[-1]
            if re.match(r"ck-[A-Za-z0-9._-]+$", basename):
                offenders.add(
                    f"{path}:{line_number}: shell command executes {basename} without a ckdev- name"
                )
    return sorted(offenders)


def _test_file_set(root: Path):
    test_files = sorted(root.glob("crates/*/tests/**/*.rs"))
    source_files = sorted(root.glob("crates/*/src/**/*.rs"))
    example_files = sorted(root.glob("crates/*/examples/**/*.rs"))
    scans = {path: SHARED.scan_structure(path) for path in source_files + example_files}
    whole_test_files: Set[Path] = set(test_files)

    pending = []
    for result in scans.values():
        pending.extend(
            (result.path, name, explicit, enclosing)
            for name, explicit, in_test, enclosing in result.modules
            if in_test
        )
    while pending:
        parent, name, explicit, enclosing = pending.pop()
        child = SHARED.module_file(parent, name, explicit, enclosing)
        if child is None:
            continue
        child = child.resolve()
        matched = next((path for path in scans if path.resolve() == child), None)
        if matched is None or matched in whole_test_files:
            continue
        whole_test_files.add(matched)
        pending.extend(
            (matched, child_name, child_path, child_enclosing)
            for child_name, child_path, _, child_enclosing in scans[matched].modules
        )

    files = []
    for path in test_files:
        files.append((path, [(0, len(SHARED.tokenize(path.read_text(encoding="utf-8", errors="replace"))))]))
    for path, result in scans.items():
        if path in whole_test_files:
            ranges = [(0, len(result.tokens))]
        else:
            ranges = result.regions
        if ranges:
            files.append((path, ranges))
    return files


def scan(root: Path) -> int:
    rust_files = _test_file_set(root)
    found: List[str] = []
    scanned_rust = 0
    for path, ranges in rust_files:
        source = path.read_text(encoding="utf-8", errors="replace")
        tokens = SHARED.tokenize(source)
        for start, end in ranges:
            found.extend(rust_token_offenders(tokens[start:end], path.relative_to(root).as_posix()))
        scanned_rust += 1

    scripts = sorted(root.glob("scripts/**/*.sh"))
    for path in scripts:
        found.extend(
            shell_offenders(path.read_text(encoding="utf-8", errors="replace"), path.relative_to(root).as_posix())
        )

    for offender in sorted(set(found)):
        print(offender, file=sys.stderr)
    print(f"scanned {scanned_rust} Rust test-code files and {len(scripts)} shell scripts for ck-* execution")
    if scanned_rust == 0 or not scripts:
        print("nothing was scanned, so ck-* execution was not checked", file=sys.stderr)
        return 2
    return 1 if found else 0


if __name__ == "__main__":
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
    sys.exit(scan(root))
