//! Deterministic mint for the on-disk browser journal vocabulary.

use serde_json::{json, Map, Value};
use sha2::{Digest, Sha256};
use std::fmt::Write;

const REVISION: &str = "browser_journal_vocabulary-v1";
const SCHEMA: &str = "ck-browser-journal-vocabulary/v1";
const WORDS: &[(&str, &[(&str, &str)])] = &[
    ("GenerationUnit", &[("Filetime100ns", "filetime_100ns")]),
    ("LaunchByteEncoding", &[("Utf16le", "utf16le")]),
    (
        "WindowsRecoveryBasis",
        &[
            ("NoIntentHolderGone", "no_intent_holder_gone"),
            ("NeverResumedHolderGone", "never_resumed_holder_gone"),
            ("GenerationsGone", "generations_gone"),
        ],
    ),
];

fn mint() -> (Vec<u8>, String, String) {
    let enums = WORDS
        .iter()
        .map(|(type_name, words)| {
            let values: Map<String, Value> = words
                .iter()
                .map(|(variant, word)| ((*variant).into(), json!(word)))
                .collect();
            (type_name.to_string(), Value::Object(values))
        })
        .collect::<Map<_, _>>();
    let bytes = serde_json::to_vec(&json!({
        "enums": enums,
        "revision": REVISION,
        "schema": SCHEMA,
    }))
    .unwrap();
    let sha = format!("{:x}", Sha256::digest(&bytes));
    let mut rust = String::from("// Generated by journal_vocabulary_mint.rs. Do not edit.\n\n");
    writeln!(
        rust,
        "#[cfg(test)]\npub const SHA256: &str =\n    \"{sha}\";"
    )
    .unwrap();
    for (type_name, words) in WORDS {
        writeln!(
            rust,
            "\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]\npub enum {type_name} {{"
        )
        .unwrap();
        for (variant, word) in *words {
            writeln!(rust, "    #[serde(rename = \"{word}\")]\n    {variant},").unwrap();
        }
        rust.push_str("}\n");
    }
    (bytes, rust, sha)
}

#[test]
fn browser_journal_vocabulary_is_the_pinned_mint() {
    let (bytes, rust, sha) = mint();
    assert_eq!(
        bytes,
        include_bytes!("../../resources/browser_journal_vocabulary-v1.json")
    );
    assert_eq!(rust, include_str!("journal_vocabulary_generated.rs"));
    assert_eq!(sha, super::journal_vocabulary::SHA256);
    let source_lock: Value = serde_json::from_slice(include_bytes!(
        "../../resources/implementation-source-lock.json"
    ))
    .unwrap();
    assert_eq!(source_lock["browser_journal_vocabulary_sha256"], sha);
}
